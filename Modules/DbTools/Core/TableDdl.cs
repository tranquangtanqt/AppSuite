using System.Text;

namespace DbTools.Core;

/// <summary>1 cột của bảng (đọc từ pg_attribute). <paramref name="Identity"/>: "a" = GENERATED ALWAYS, "d" = BY DEFAULT, rỗng = không.
/// <paramref name="Generated"/>: biểu thức cột tính (GENERATED ALWAYS AS (...) STORED), rỗng = không.</summary>
public sealed record ColumnInfo(int Number, string Name, string Type, bool NotNull, string Default, string Identity, string Generated,
    string Collation, string Comment)
{
    public string NullText => NotNull ? "NOT NULL" : string.Empty;

    /// <summary>Giá trị mặc định / identity / cột tính để hiện trong bảng cột.</summary>
    public string DefaultText => Identity switch
    {
        "a" => "GENERATED ALWAYS AS IDENTITY",
        "d" => "GENERATED BY DEFAULT AS IDENTITY",
        _ => Generated.Length > 0 ? $"GENERATED ALWAYS AS ({Generated}) STORED" : Default,
    };
}

/// <summary>Ràng buộc: <paramref name="Type"/> p (khoá chính), u (duy nhất), f (khoá ngoại), c (check), x (exclusion).
/// <paramref name="Definition"/> = pg_get_constraintdef.</summary>
public sealed record ConstraintInfo(string Name, string Type, string Definition)
{
    public string TypeText => Type switch
    {
        "p" => "Khoá chính",
        "u" => "Duy nhất",
        "f" => "Khoá ngoại",
        "c" => "Check",
        "x" => "Exclusion",
        "n" => "Not null",
        _ => Type,
    };
}

/// <summary>Index: <paramref name="Definition"/> = pg_get_indexdef. <paramref name="ForConstraint"/>: index do khoá chính / duy nhất tạo ra
/// (DDL không viết riêng - ràng buộc tự tạo lại).</summary>
public sealed record IndexInfo(string Name, string Definition, bool Unique, bool Primary, bool ForConstraint, long SizeBytes);

/// <summary>Trigger: <paramref name="Definition"/> = pg_get_triggerdef. <paramref name="Enabled"/>: O (bật), D (tắt), R / A (replica / always).</summary>
public sealed record TriggerInfo(string Name, string Definition, string Enabled, string Function)
{
    public bool Disabled => Enabled == "D";
}

/// <summary>Chi tiết 1 bảng (hoặc bảng phân vùng / bảng ngoài) để xem cấu trúc + dựng DDL.</summary>
public sealed class TableDetail
{
    public string Schema { get; init; } = string.Empty;
    public string Name { get; init; } = string.Empty;

    /// <summary>r bảng thường, p bảng phân vùng, f bảng ngoài.</summary>
    public string Kind { get; init; } = "r";
    public string Owner { get; init; } = string.Empty;
    public string Comment { get; init; } = string.Empty;

    /// <summary>"PARTITION BY ..." (pg_get_partkeydef) khi là bảng phân vùng.</summary>
    public string PartitionKey { get; init; } = string.Empty;

    /// <summary>"PARTITION OF cha FOR VALUES ..." khi là 1 phân vùng con.</summary>
    public string PartitionOf { get; init; } = string.Empty;
    public string Inherits { get; init; } = string.Empty;
    public bool Unlogged { get; init; }
    public List<ColumnInfo> Columns { get; init; } = [];
    public List<ConstraintInfo> Constraints { get; init; } = [];
    public List<IndexInfo> Indexes { get; init; } = [];
    public List<TriggerInfo> Triggers { get; init; } = [];

    public string QualifiedName => $"{PgSql.QuoteIdentIfNeeded(Schema)}.{PgSql.QuoteIdentIfNeeded(Name)}";

    /// <summary>Cột nằm trong khoá chính (để đánh dấu 🔑 trong bảng cột).</summary>
    public HashSet<string> PrimaryKeyColumns { get; init; } = new(StringComparer.Ordinal);

    /// <summary>Cột là khoá ngoại → bảng được tham chiếu, vd "customer(id)".</summary>
    public Dictionary<string, string> ForeignKeyColumns { get; init; } = new(StringComparer.Ordinal);
}

/// <summary>
/// Dựng DDL của 1 bảng từ catalog (PostgreSQL không có pg_get_tabledef): CREATE TABLE (cột, kiểu, NOT NULL, DEFAULT / identity / cột
/// tính, COLLATE) → ALTER TABLE ADD CONSTRAINT (khoá chính, duy nhất, check, khoá ngoại) → CREATE INDEX (index không thuộc ràng
/// buộc) → CREATE TRIGGER (+ DISABLE nếu đang tắt) → COMMENT ON. Giống thứ tự pg_dump in ra để đọc / chép lại quen mắt.
/// </summary>
public static class TableDdl
{
    public static string Build(TableDetail t)
    {
        var sb = new StringBuilder();
        var name = t.QualifiedName;
        sb.Append(t.Kind == "f" ? "CREATE FOREIGN TABLE " : t.Unlogged ? "CREATE UNLOGGED TABLE " : "CREATE TABLE ").Append(name);
        if (t.PartitionOf.Length > 0)
        {
            sb.Append(' ').Append(t.PartitionOf);
        }
        else
        {
            sb.AppendLine(" (");
            for (var i = 0; i < t.Columns.Count; i++)
            {
                var c = t.Columns[i];
                sb.Append("    ").Append(PgSql.QuoteIdentIfNeeded(c.Name)).Append(' ').Append(c.Type);
                if (c.Collation.Length > 0)
                {
                    sb.Append(" COLLATE ").Append(c.Collation);
                }
                if (c.Identity.Length > 0 || c.Generated.Length > 0)
                {
                    sb.Append(' ').Append(c.DefaultText);
                }
                else if (c.Default.Length > 0)
                {
                    sb.Append(" DEFAULT ").Append(c.Default);
                }
                if (c.NotNull)
                {
                    sb.Append(" NOT NULL");
                }
                sb.AppendLine(i < t.Columns.Count - 1 ? "," : string.Empty);
            }
            sb.Append(')');
            if (t.Inherits.Length > 0)
            {
                sb.Append(" INHERITS (").Append(t.Inherits).Append(')');
            }
        }
        if (t.PartitionKey.Length > 0)
        {
            sb.Append(' ').Append(t.PartitionKey);
        }
        sb.AppendLine(";");

        // Khoá chính / duy nhất / check trước, khoá ngoại sau cùng (như pg_dump).
        var constraints = t.Constraints.Where(c => c.Type != "n").OrderBy(c => c.Type == "f" ? 1 : 0).ThenBy(c => c.Name, StringComparer.Ordinal).ToList();
        if (constraints.Count > 0)
        {
            sb.AppendLine();
            foreach (var c in constraints)
            {
                sb.AppendLine($"ALTER TABLE {name} ADD CONSTRAINT {PgSql.QuoteIdentIfNeeded(c.Name)} {c.Definition};");
            }
        }
        var indexes = t.Indexes.Where(i => !i.ForConstraint).ToList();
        if (indexes.Count > 0)
        {
            sb.AppendLine();
            foreach (var i in indexes)
            {
                sb.AppendLine(i.Definition + ";");
            }
        }
        if (t.Triggers.Count > 0)
        {
            sb.AppendLine();
            foreach (var tr in t.Triggers)
            {
                sb.AppendLine(tr.Definition + ";");
                if (tr.Disabled)
                {
                    sb.AppendLine($"ALTER TABLE {name} DISABLE TRIGGER {PgSql.QuoteIdentIfNeeded(tr.Name)};");
                }
            }
        }
        var comments = new List<string>();
        if (t.Comment.Length > 0)
        {
            comments.Add($"COMMENT ON TABLE {name} IS {PgSql.Literal(t.Comment)};");
        }
        comments.AddRange(t.Columns.Where(c => c.Comment.Length > 0)
            .Select(c => $"COMMENT ON COLUMN {name}.{PgSql.QuoteIdentIfNeeded(c.Name)} IS {PgSql.Literal(c.Comment)};"));
        if (comments.Count > 0)
        {
            sb.AppendLine();
            comments.ForEach(c => sb.AppendLine(c));
        }
        return sb.ToString();
    }
}
