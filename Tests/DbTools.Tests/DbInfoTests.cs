namespace DbTools.Tests;

/// <summary>Trang Thông tin DB: dựng DDL bảng, đọc catalog (tổng quan, bảng, đối tượng, chi tiết bảng).</summary>
public class DbInfoTests
{
    [Theory]
    [InlineData("order_no", "order_no")]
    [InlineData("msta_x_$s", "msta_x_$s")]
    [InlineData("Order", "\"Order\"")]
    [InlineData("user", "\"user\"")]
    [InlineData("1abc", "\"1abc\"")]
    [InlineData("a b", "\"a b\"")]
    public void Quotes_identifiers_only_when_needed(string name, string expected)
    {
        Assert.Equal(expected, PgSql.QuoteIdentIfNeeded(name));
    }

    [Fact]
    public void Builds_table_ddl_in_pg_dump_order()
    {
        var t = new TableDetail
        {
            Schema = "public",
            Name = "app_order",
            Comment = "đơn hàng's",
            Columns =
            [
                new ColumnInfo(1, "id", "bigint", true, "", "a", "", "", ""),
                new ColumnInfo(2, "cust_id", "integer", true, "", "", "", "", "khách"),
                new ColumnInfo(3, "amount", "numeric(15,2)", false, "0", "", "", "", ""),
                new ColumnInfo(4, "total", "numeric", false, "", "", "(amount * 2)", "", ""),
                new ColumnInfo(5, "Note", "text", false, "", "", "", "\"C\"", ""),
            ],
            Constraints =
            [
                new ConstraintInfo("app_order_cust_fk", "f", "FOREIGN KEY (cust_id) REFERENCES cust(id)"),
                new ConstraintInfo("app_order_pk", "p", "PRIMARY KEY (id)"),
                new ConstraintInfo("app_order_ck", "c", "CHECK (amount >= 0::numeric)"),
                new ConstraintInfo("app_order_id_not_null", "n", "NOT NULL id"),
            ],
            Indexes =
            [
                new IndexInfo("app_order_pk", "CREATE UNIQUE INDEX app_order_pk ON public.app_order USING btree (id)", true, true, true, 8192),
                new IndexInfo("app_order_ie01", "CREATE INDEX app_order_ie01 ON public.app_order USING btree (cust_id)", false, false, false, 8192),
            ],
            Triggers = [new TriggerInfo("app_order_tr", "CREATE TRIGGER app_order_tr BEFORE INSERT ON app_order FOR EACH ROW EXECUTE FUNCTION f()", "D", "f")],
        };
        var ddl = TableDdl.Build(t);
        Assert.Equal("""
            CREATE TABLE public.app_order (
                id bigint GENERATED ALWAYS AS IDENTITY NOT NULL,
                cust_id integer NOT NULL,
                amount numeric(15,2) DEFAULT 0,
                total numeric GENERATED ALWAYS AS ((amount * 2)) STORED,
                "Note" text COLLATE "C"
            );

            ALTER TABLE public.app_order ADD CONSTRAINT app_order_ck CHECK (amount >= 0::numeric);
            ALTER TABLE public.app_order ADD CONSTRAINT app_order_pk PRIMARY KEY (id);
            ALTER TABLE public.app_order ADD CONSTRAINT app_order_cust_fk FOREIGN KEY (cust_id) REFERENCES cust(id);

            CREATE INDEX app_order_ie01 ON public.app_order USING btree (cust_id);

            CREATE TRIGGER app_order_tr BEFORE INSERT ON app_order FOR EACH ROW EXECUTE FUNCTION f();
            ALTER TABLE public.app_order DISABLE TRIGGER app_order_tr;

            COMMENT ON TABLE public.app_order IS 'đơn hàng''s';
            COMMENT ON COLUMN public.app_order.cust_id IS 'khách';

            """.Replace("\r\n", "\n"), ddl.Replace("\r\n", "\n"));
    }

    [Fact]
    public void Partition_child_uses_partition_of()
    {
        var ddl = TableDdl.Build(new TableDetail
        {
            Schema = "public",
            Name = "log_2026",
            PartitionOf = "PARTITION OF log FOR VALUES FROM ('2026-01-01') TO ('2027-01-01')",
            Columns = [new ColumnInfo(1, "at", "date", false, "", "", "", "", "")],
        });
        Assert.StartsWith("CREATE TABLE public.log_2026 PARTITION OF log FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');", ddl);
    }
}

/// <summary>Đọc catalog thật (cần DBTOOLS_TEST_PG). DDL khứ hồi: dựng DDL → chạy vào DB trống → dựng lại phải giống hệt.</summary>
public sealed class PgInfoIntegrationTests : IAsyncLifetime
{
    private static readonly string? Server = Environment.GetEnvironmentVariable("DBTOOLS_TEST_PG");
    private readonly string _db = "dbtools_info_" + Guid.NewGuid().ToString("N")[..10];
    private ConnectionProfile _admin = new();

    private const string Schema = """
        CREATE SCHEMA addon;
        CREATE SEQUENCE addon.no_seq START 100 INCREMENT 5;
        CREATE TABLE addon.cust (id int PRIMARY KEY, name text NOT NULL);
        COMMENT ON TABLE addon.cust IS 'khách hàng';
        CREATE TABLE addon."Order" (
            id bigint GENERATED BY DEFAULT AS IDENTITY,
            no int DEFAULT nextval('addon.no_seq'),
            cust_id int NOT NULL REFERENCES addon.cust(id) ON DELETE CASCADE,
            amount numeric(15,2) DEFAULT 0 CHECK (amount >= 0),
            doubled numeric GENERATED ALWAYS AS (amount * 2) STORED,
            memo varchar(200) COLLATE "C",
            CONSTRAINT order_pk PRIMARY KEY (id),
            CONSTRAINT order_no_uk UNIQUE (no)
        );
        CREATE INDEX order_ie01 ON addon."Order" (cust_id, amount DESC) WHERE amount > 0;
        COMMENT ON COLUMN addon."Order".memo IS 'ghi chú ''x''';
        CREATE FUNCTION addon.tr_f() RETURNS trigger AS $$ BEGIN RETURN NEW; END $$ LANGUAGE plpgsql;
        CREATE TRIGGER order_tr BEFORE INSERT ON addon."Order" FOR EACH ROW EXECUTE FUNCTION addon.tr_f();
        ALTER TABLE addon."Order" DISABLE TRIGGER order_tr;
        CREATE VIEW addon.order_v AS SELECT id, amount FROM addon."Order" WHERE amount > 0;
        CREATE TABLE addon.log (at date NOT NULL, msg text) PARTITION BY RANGE (at);
        CREATE TABLE addon.log_2026 PARTITION OF addon.log FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
        INSERT INTO addon.cust SELECT g, 'k' || g FROM generate_series(1, 30) g;
        """;

    public async ValueTask InitializeAsync()
    {
        if (string.IsNullOrEmpty(Server))
        {
            return;
        }
        var b = new NpgsqlConnectionStringBuilder(Server);
        _admin = new ConnectionProfile { Host = b.Host!, Port = b.Port, Username = b.Username!, Password = b.Password ?? "", Database = "postgres" };
        await PgAdmin.CreateDatabaseAsync(_admin, _db, CancellationToken.None);
        await PgAdmin.CreateDatabaseAsync(_admin, _db + "_b", CancellationToken.None);
        await ExecAsync(_db, Schema);
    }

    public async ValueTask DisposeAsync()
    {
        if (string.IsNullOrEmpty(Server))
        {
            return;
        }
        await using var c = await Pg.OpenAsync(_admin, CancellationToken.None);
        foreach (var db in new[] { _db, _db + "_b" })
        {
            await using var cmd = new NpgsqlCommand($"DROP DATABASE IF EXISTS {db} WITH (FORCE)", c);
            await cmd.ExecuteNonQueryAsync();
        }
    }

    private async Task ExecAsync(string db, string sql)
    {
        await using var c = await PgInfo.OpenAsync(_admin, db, CancellationToken.None);
        foreach (var s in SqlSplitter.Split(sql).Statements)
        {
            await using var cmd = new NpgsqlCommand(s.Text, c);
            await cmd.ExecuteNonQueryAsync();
        }
    }

    [Fact]
    public async Task Reads_overview_tables_and_objects()
    {
        Assert.SkipWhen(string.IsNullOrEmpty(Server), "Chưa đặt DBTOOLS_TEST_PG.");
        await using var c = await PgInfo.OpenAsync(_admin, _db, CancellationToken.None);
        var o = await PgInfo.OverviewAsync(c, CancellationToken.None);
        Assert.Equal(_db, o.Database);
        Assert.Equal("UTF8", o.Encoding);
        Assert.True(o.SizeBytes > 0);
        Assert.True(o.Sessions >= 1);

        var addon = Assert.Single(await PgInfo.SchemasAsync(c, CancellationToken.None), s => s.Schema == "addon");
        Assert.Equal(4, addon.Tables); // cust, Order, log, log_2026
        Assert.Equal(1, addon.Views);
        Assert.Equal(1, addon.Functions);
        Assert.Equal(1, addon.Triggers);
        Assert.Equal(2, addon.Sequences); // no_seq + identity của Order.id

        var tables = await PgInfo.TablesAsync(c, CancellationToken.None);
        var cust = Assert.Single(tables, t => t.Name == "cust");
        Assert.True(cust.HasPrimaryKey);
        Assert.Equal("khách hàng", cust.Comment);
        Assert.Equal(2, cust.Columns);
        Assert.Equal(30L, await PgInfo.CountRowsAsync(c, "addon", "cust", CancellationToken.None));
        Assert.Equal("p", Assert.Single(tables, t => t.Name == "log").Kind);
        Assert.True(Assert.Single(tables, t => t.Name == "log_2026").IsPartition);
        Assert.DoesNotContain(tables, t => t.Schema is "pg_catalog" or "information_schema");

        var objects = await PgInfo.ObjectsAsync(c, CancellationToken.None);
        var view = Assert.Single(objects, x => x.Kind == "view" && x.Name == "order_v");
        Assert.StartsWith("CREATE OR REPLACE VIEW addon.order_v AS", await PgInfo.DefinitionAsync(c, view, CancellationToken.None));
        var fn = Assert.Single(objects, x => x.Kind == "function" && x.Name == "tr_f");
        Assert.Contains("→ trigger · plpgsql", fn.Info);
        Assert.Contains("CREATE OR REPLACE FUNCTION addon.tr_f()", await PgInfo.DefinitionAsync(c, fn, CancellationToken.None));
        var tr = Assert.Single(objects, x => x.Kind == "trigger");
        Assert.Contains("ĐANG TẮT", tr.Info);
        Assert.StartsWith("CREATE TRIGGER order_tr BEFORE INSERT ON addon.\"Order\"", await PgInfo.DefinitionAsync(c, tr, CancellationToken.None));
        var seq = Assert.Single(objects, x => x.Kind == "sequence" && x.Name == "no_seq");
        Assert.Contains("INCREMENT BY 5", seq.Definition);
        Assert.Contains("START WITH 100", seq.Definition);
        Assert.Contains(objects, x => x.Kind == "extension" && x.Name == "plpgsql");
    }

    [Fact]
    public async Task Table_detail_and_ddl_round_trip()
    {
        Assert.SkipWhen(string.IsNullOrEmpty(Server), "Chưa đặt DBTOOLS_TEST_PG.");
        string ddl;
        await using (var c = await PgInfo.OpenAsync(_admin, _db, CancellationToken.None))
        {
            var tables = await PgInfo.TablesAsync(c, CancellationToken.None);
            var order = await PgInfo.TableDetailAsync(c, tables.Single(t => t.Name == "Order").Oid, CancellationToken.None);
            Assert.Equal(["id", "no", "cust_id", "amount", "doubled", "memo"], order.Columns.Select(x => x.Name));
            Assert.Equal("d", order.Columns[0].Identity);
            Assert.Equal("numeric(15,2)", order.Columns[3].Type);
            Assert.Contains("amount * ", order.Columns[4].Generated);
            Assert.Equal("\"C\"", order.Columns[5].Collation);
            Assert.Equal("ghi chú 'x'", order.Columns[5].Comment);
            Assert.Contains("id", order.PrimaryKeyColumns);
            Assert.Equal("addon.cust(id)", order.ForeignKeyColumns["cust_id"]);
            Assert.Contains(order.Constraints, k => k.Type == "f" && k.Definition.Contains("ON DELETE CASCADE"));
            Assert.Contains(order.Indexes, i => i.Name == "order_ie01" && !i.ForConstraint && i.Definition.Contains("WHERE"));
            Assert.Contains(order.Indexes, i => i.Name == "order_pk" && i.ForConstraint);
            Assert.True(Assert.Single(order.Triggers).Disabled);

            var log = await PgInfo.TableDetailAsync(c, tables.Single(t => t.Name == "log").Oid, CancellationToken.None);
            Assert.Equal("PARTITION BY RANGE (at)", log.PartitionKey);
            var part = await PgInfo.TableDetailAsync(c, tables.Single(t => t.Name == "log_2026").Oid, CancellationToken.None);
            Assert.StartsWith("PARTITION OF addon.log FOR VALUES FROM ('2026-01-01') TO ('2027-01-01')", part.PartitionOf);

            ddl = string.Join("\n", new[] { "cust", "Order", "log", "log_2026" }
                .Select(n => tables.Single(t => t.Name == n).Oid)
                .Select(oid => PgInfo.TableDetailAsync(c, oid, CancellationToken.None).Result)
                .Select(TableDdl.Build));
        }

        // DB trống chỉ có schema, sequence, hàm nền → chạy DDL dựng ra → đọc lại → DDL y hệt.
        await ExecAsync(_db + "_b", """
            CREATE SCHEMA addon;
            CREATE SEQUENCE addon.no_seq START 100 INCREMENT 5;
            CREATE FUNCTION addon.tr_f() RETURNS trigger AS $$ BEGIN RETURN NEW; END $$ LANGUAGE plpgsql;
            """);
        await ExecAsync(_db + "_b", ddl);
        await using (var c = await PgInfo.OpenAsync(_admin, _db + "_b", CancellationToken.None))
        {
            var tables = await PgInfo.TablesAsync(c, CancellationToken.None);
            var again = string.Join("\n", new[] { "cust", "Order", "log", "log_2026" }
                .Select(n => tables.Single(t => t.Name == n).Oid)
                .Select(oid => PgInfo.TableDetailAsync(c, oid, CancellationToken.None).Result)
                .Select(TableDdl.Build));
            Assert.Equal(ddl, again);
        }
    }
}
